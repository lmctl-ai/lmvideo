// Everything a chunk creates lives here for one run of the chunk and dies after it; handles cannot be stored across runs.
class Arena {
 public:
  template <class T, class... A>
  T* make(A&&... a) {
    auto p = std::make_shared<T>(std::forward<A>(a)...);
    items_.push_back(p);
    return p.get();
  }
  void clear() { items_.clear(); }

 private:
  std::deque<std::shared_ptr<void>> items_;
};

// A Canvas is a non-owning view; the slot is empty until video.begin().
struct CanvasSlot {
  std::optional<lmv::Canvas> canvas;
  lmv::Canvas& get() {
    if (!canvas) throw dslvm::Error("Canvas is not available before video.begin()");
    return *canvas;
  }
};

struct SurfaceObj {
  SurfaceObj(int w, int h) : surface(w, h) { slot.canvas = surface.canvas(); }
  lmv::Surface surface;
  CanvasSlot slot;
};

