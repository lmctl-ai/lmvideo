// --dsl-schema: the shared summary (context/fn lines, then per owner `Owner:` and indented methods).
static void print_schema_summary(const dslvm::Registry& reg) {
  std::vector<std::string> order; std::map<std::string, std::vector<std::string>> members;
  for (const auto& s : reg.signatures()) {
    if (s.rfind("context ", 0) == 0 || s.rfind("fn ", 0) == 0) std::cout << s << "\n";
    else if (s.rfind("method ", 0) == 0) { std::string body = s.substr(7), owner = body.substr(0, body.find('.')); if (!members.count(owner)) order.push_back(owner); members[owner].push_back(body); }
  }
  for (const auto& owner : order) { std::cout << owner << ":\n"; for (const auto& m : members[owner]) std::cout << "  " << m << "\n"; }
}

int host_main(int argc, char** argv) {
  const char* usage = "usage: lmvideo --dsl FILE.dslb [--output PATH] | --dsl-schema [--json] | --dsl-signatures | --version | demo OUT.png | render IN.svg OUT.png\n";
  const std::string schema_bytes(reinterpret_cast<const char*>(lmvideo_dsl::embedded_schema), lmvideo_dsl::embedded_schema_size);
  auto print_signatures = [](bool summary) {  // the registry's canonical signatures as the host declares them
    Arena pa; OutputState po; dslvm::Registry preg; schema::Schema empty; Registrar pr(preg, empty);
    register_schema(pr, pa, po);
    if (summary) print_schema_summary(preg); else for (const auto& s : preg.signatures()) std::cout << s << "\n";
    return std::cout ? 0 : 4;
  };
  if (argc >= 2 && std::string(argv[1]) == "--dsl-schema") {
    if (argc == 3 && std::string(argv[2]) == "--json") { std::cout.write(schema_bytes.data(), std::streamsize(schema_bytes.size())); return std::cout ? 0 : 4; }
    if (argc != 2) { std::cerr << usage; return 2; }
    return print_signatures(true);
  }
  if (argc == 2 && std::string(argv[1]) == "--dsl-signatures") return print_signatures(false);
  std::string dsl_path, output_override;
  for (int i = 1; i < argc; ++i) {
    std::string a = argv[i];
    auto value = [&]() {
      if (i + 1 >= argc || std::string(argv[i + 1]).rfind("--", 0) == 0) { std::cerr << usage; std::exit(2); }
      return std::string(argv[++i]);
    };
    if (a == "--dsl") dsl_path = value();
    else if (a == "--output") output_override = value();
    else { std::cerr << usage; return 2; }
  }
  if (dsl_path.empty()) { std::cerr << usage; return 2; }

  // (1) Register the schema's implementation, then load and verify the bytecode; nothing has run yet.
  Arena arena;
  VideoState video;
  OutputState output;
  dslvm::Registry reg;
  dslvm::Program program;
  std::string bytecode_bytes;
  schema::Schema schema;  // outlives the run: the registered closures point into it
  std::optional<Registrar> registrar_slot;
  try {
    schema = schema::parse(schema_bytes);
    Registrar& registrar = registrar_slot.emplace(reg, schema);
    register_schema(registrar, arena, output);
    registrar.verify();  // the registry IS the schema, or nothing starts
    bytecode_bytes = dslvm::read_file(dsl_path);
    program = dslvm::Program::load(bytecode_bytes, schema_bytes, reg);
  } catch (const dslvm::Error& e) {  // refused before anything ran: one JSON line, phase load, exit 3
    std::cerr << "error: " << dsl_path << ": " << e.what() << "\n";
    return dslvm::report_error("load", e);
  }

  CanvasSlot main_canvas;
  video.canvas_slot = &main_canvas;
  video.override_output = output_override;
  dslvm::Context ctx;
  ctx.set("canvas", &main_canvas);
  ctx.set("video", &video);
  ctx.set("out", &output);

  try {
    // The chunk configures and renders in one invocation. Video.begin() allocates
    // the host-owned surface/encoder; frame() clears and advances the current frame.
    dslvm::Program::RunStats stats;
    auto started = std::chrono::steady_clock::now();
    program.run(ctx, reg, &stats);
    auto elapsed_ms = std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::steady_clock::now() - started).count();
    if (output.failed) { std::cerr << "fail: " << output.failure << "\n"; return dslvm::report_app_failure(output.failure); }
    if (!video.ended) throw dslvm::Error("the chunk did not call video.end()");
    bool image = is_image_path(video.output);

    // (4) Report: the human line on stderr, then exactly one JSON result line on stdout (A03) with every out.print line in order.
    if (image) std::cerr << "wrote " << video.output << " (" << video.width << "x" << video.height << ")\n";
    else std::cerr << "wrote " << video.output << " (" << video.width << "x" << video.height << ", " << video.frames << " frames at " << video.fps << " fps)\n";
    std::string lines;
    for (const auto& l : output.lines) lines += (lines.empty() ? "" : ", ") + dslvm::json_escape(l);
    return dslvm::report_ok("{\"output\": [" + lines + "], \"file\": " + dslvm::json_escape(video.output) + ", \"width\": " + std::to_string(video.width) +
                            ", \"height\": " + std::to_string(video.height) + ", \"frames\": " + std::to_string(video.frames) + ", \"fps\": " + std::to_string(video.fps) +
                            ", \"bytecode_bytes\": " + std::to_string(bytecode_bytes.size()) + ", \"instructions\": " + std::to_string(stats.instructions) +
                            ", \"wall_ms\": " + std::to_string(elapsed_ms) + "}");
  } catch (const dslvm::Error& e) {  // the VM (RUN_ERROR) or a host method (RUN_HOST): phase run, exit 3
    if (output.failed) { std::cerr << "fail: " << output.failure << "\n"; return dslvm::report_error("app", e); }
    std::cerr << "dsl runtime error: " << e.what() << "\n";
    return dslvm::report_error("run", e);
  } catch (const lmv::Error& e) {  // the library outside a method (encoder, image writer): phase run, RUN_HOST, exit 3
    std::cerr << "error: " << e.what() << "\n";
    return dslvm::report_error("run", dslvm::Error(e.what()));
  }
}
